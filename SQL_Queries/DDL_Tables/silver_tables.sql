-- -----------------------------------------------------
-- fact_sales: grain = one order line, all 3 sources
--   AW22: SalesOrderHeader + SalesOrderDetail (order = salesorderid, line = salesorderdetailid)
--   NW1 : Orders + [Order Details]            (order = orderid,      line = productid)
--   CNK1: Invoice + InvoiceLine               (order = invoiceid,    line = invoicelineid)
-- Header-level freight / tax are allocated to lines proportionally to line_total
-- -----------------------------------------------------
CREATE TABLE silver.fact_sales (
    sales_key           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    src_sys_id          VARCHAR(10)  NOT NULL,
    src_order_id        VARCHAR(50)  NOT NULL,
    src_line_id         VARCHAR(50)  NOT NULL,

    product_key         BIGINT NOT NULL DEFAULT -1 REFERENCES silver.dim_product (product_key),
    customer_key        BIGINT NOT NULL DEFAULT -1 REFERENCES silver.dim_person (person_key),
    employee_key        BIGINT NOT NULL DEFAULT -1 REFERENCES silver.dim_person (person_key),  -- sales person / support rep
    ship_geography_key  BIGINT NOT NULL DEFAULT -1 REFERENCES silver.dim_geography (geography_key),
    territory_key       BIGINT NOT NULL DEFAULT -1 REFERENCES silver.dim_sales_territory (territory_key),
    shipper_key         BIGINT NOT NULL DEFAULT -1 REFERENCES silver.dim_shipper (shipper_key),

    order_date          DATE,
    due_date            DATE,
    ship_date           DATE,

    quantity            NUMERIC(18,4),
    unit_price          NUMERIC(19,4),
    discount            NUMERIC(9,4),            -- fraction (0.10 = 10%)
    line_total          NUMERIC(19,4),           -- quantity * unit_price * (1 - discount)
    allocated_freight   NUMERIC(19,4),
    allocated_tax       NUMERIC(19,4),

    load_dts            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    batch_id            BIGINT       NOT NULL,
    CONSTRAINT uq_fact_sales_bk   UNIQUE (src_sys_id, src_order_id, src_line_id),
    CONSTRAINT chk_fact_sales_src CHECK (src_sys_id IN ('AW22', 'NW1', 'CNK1'))
);

CREATE INDEX ix_fact_sales_product   ON silver.fact_sales (product_key);
CREATE INDEX ix_fact_sales_customer  ON silver.fact_sales (customer_key);
CREATE INDEX ix_fact_sales_employee  ON silver.fact_sales (employee_key);
CREATE INDEX ix_fact_sales_geography ON silver.fact_sales (ship_geography_key);
CREATE INDEX ix_fact_sales_territory ON silver.fact_sales (territory_key);
CREATE INDEX ix_fact_sales_shipper   ON silver.fact_sales (shipper_key);
CREATE INDEX ix_fact_sales_orderdate ON silver.fact_sales (order_date);

-- -----------------------------------------------------
-- fact_purchase: grain = one purchase order line (AW22 PurchaseOrderHeader + Detail)
