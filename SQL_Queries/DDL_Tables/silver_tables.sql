-- =====================================================
-- SILVER layer = DWH core: all tables with PRIMARY KEY and FOREIGN KEYs
--
-- Dimensions : dim_geography, dim_person, dim_product, dim_supplier,
--              dim_shipper, dim_sales_territory
-- Facts      : fact_sales, fact_purchase, fact_work_order
--
-- Every table: surrogate key + src_sys_id ('AW22'|'NW1'|'CNK1') + source ID (src_*_id)
--              + load_dts + batch_id
-- SCD2 (is_current + row_hash, no valid_from/valid_to): dim_person, dim_product
-- SCD1 (update in place): all other dimensions
-- Unknown member: surrogate key -1 in every dimension (src_sys_id = 'N/A')
-- Facts: dates stored directly (no dim_date); FK columns default to -1 (unknown)
--
-- Create order: dim_geography -> other dims -> facts (script handles it)
-- Requires PostgreSQL 15+ (MERGE, used later in the load procedures)
-- =====================================================
CREATE SCHEMA IF NOT EXISTS silver;

DROP TABLE IF EXISTS silver.fact_sales          CASCADE;
DROP TABLE IF EXISTS silver.fact_purchase       CASCADE;
DROP TABLE IF EXISTS silver.fact_work_order     CASCADE;
DROP TABLE IF EXISTS silver.dim_person          CASCADE;
DROP TABLE IF EXISTS silver.dim_product         CASCADE;
DROP TABLE IF EXISTS silver.dim_supplier        CASCADE;
DROP TABLE IF EXISTS silver.dim_shipper         CASCADE;
DROP TABLE IF EXISTS silver.dim_sales_territory CASCADE;
DROP TABLE IF EXISTS silver.dim_geography       CASCADE;

-- -----------------------------------------------------
-- dim_geography (SCD1): one row per source + country + state + city
-- -----------------------------------------------------
CREATE TABLE silver.dim_geography (
    geography_key   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    src_sys_id      VARCHAR(10)  NOT NULL,
    src_geo_id      VARCHAR(400) NOT NULL,   -- country|state_province|city (source has no ID for city)
    country_code    VARCHAR(10),             -- AW22 only (CountryRegionCode)
    country         VARCHAR(100) NOT NULL,   -- 'N/A' when missing
    state_province  VARCHAR(100) NOT NULL,
    city            VARCHAR(100) NOT NULL,
    load_dts        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    batch_id        BIGINT       NOT NULL,
    CONSTRAINT uq_dim_geography_bk UNIQUE (src_sys_id, src_geo_id),
    CONSTRAINT chk_dim_geography_src CHECK (src_sys_id IN ('AW22', 'NW1', 'CNK1', 'N/A'))
);

INSERT INTO silver.dim_geography
    (geography_key, src_sys_id, src_geo_id, country_code, country, state_province, city, batch_id)
VALUES (-1, 'N/A', '-1', NULL, 'N/A', 'N/A', 'N/A', 0);

-- -----------------------------------------------------
-- dim_person (SCD2): customers + employees from all 3 sources
-- business key: (src_sys_id, person_type, src_person_id)
--   person_type is in the key: customer and employee IDs overlap inside one source
-- -----------------------------------------------------
CREATE TABLE silver.dim_person (
    person_key         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    src_sys_id         VARCHAR(10)  NOT NULL,
    person_type        VARCHAR(10)  NOT NULL,   -- 'CUSTOMER' | 'EMPLOYEE'
    src_person_id      VARCHAR(50)  NOT NULL,   -- source ID as text (NW1 customer id = 'ALFKI')

    customer_kind      VARCHAR(10),             -- AW22: 'INDIVIDUAL' | 'COMPANY'
    first_name         VARCHAR(100),
    last_name          VARCHAR(100),
    full_name          VARCHAR(250),
    company_name       VARCHAR(150),
    job_title          VARCHAR(100),
    birth_date         DATE,
    hire_date          DATE,
    gender             VARCHAR(10),             -- AW22 employee only
    marital_status     VARCHAR(10),             -- AW22 employee only
    email              VARCHAR(150),            -- AW22: NULL (EmailAddress table not in bronze)
    phone              VARCHAR(50),             -- AW22: NULL (PersonPhone table not in bronze)
    fax                VARCHAR(50),
    address_line       VARCHAR(200),
    postal_code        VARCHAR(20),
    geography_key      BIGINT       NOT NULL DEFAULT -1 REFERENCES silver.dim_geography (geography_key),
    manager_src_id     VARCHAR(50),             -- NW1/CNK1 reportsto
    territory_src_id   VARCHAR(50),             -- AW22 territoryid
    support_rep_src_id VARCHAR(50),             -- CNK1 customer.supportrepid

    is_current         BOOLEAN      NOT NULL DEFAULT TRUE,
    row_hash           CHAR(32)     NOT NULL,   -- md5 of tracked attributes (change detection)
    load_dts           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    batch_id           BIGINT       NOT NULL,
    CONSTRAINT chk_dim_person_src  CHECK (src_sys_id IN ('AW22', 'NW1', 'CNK1', 'N/A')),
    CONSTRAINT chk_dim_person_type CHECK (person_type IN ('CUSTOMER', 'EMPLOYEE', 'N/A'))
);

-- only one current version per business key
CREATE UNIQUE INDEX ux_dim_person_bk
    ON silver.dim_person (src_sys_id, person_type, src_person_id) WHERE is_current;

INSERT INTO silver.dim_person
    (person_key, src_sys_id, person_type, src_person_id, full_name, row_hash, batch_id)
VALUES (-1, 'N/A', 'N/A', '-1', 'Unknown', md5('unknown'), 0);

