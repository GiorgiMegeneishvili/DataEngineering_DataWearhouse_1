    order_qty           NUMERIC(18,4),
    received_qty        NUMERIC(18,4),
    rejected_qty        NUMERIC(18,4),
    unit_price          NUMERIC(19,4),
    line_total          NUMERIC(19,4),           -- order_qty * unit_price
    allocated_freight   NUMERIC(19,4),
    allocated_tax       NUMERIC(19,4),

    load_dts            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    batch_id            BIGINT       NOT NULL,
